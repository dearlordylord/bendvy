"""Mandatory finite fused suppression, using the same fresh frozen-overlay Tx baseline."""
import copy,hashlib,importlib.util,json,os,re
from pathlib import Path
import shutil
import provider_controls as PC
HERE=Path(__file__).resolve().parent;ROOT=HERE.parents[2]
STATUS='PASS_LIVE_NOOP_TRUEOLD_JOURNAL_MARK_FULLFIELDS_BOTH'
def sha(path):return hashlib.sha256(Path(path).read_bytes()).hexdigest()
def load(name,path):
    spec=importlib.util.spec_from_file_location(name,path);module=importlib.util.module_from_spec(spec);spec.loader.exec_module(module);return module

def expected_noop(baseline):
    assert len(baseline)==144
    expected=copy.deepcopy(baseline)
    for scenario in (0,8):
        for offset in (2,3,6,10,11,14):
            record=expected[scenario*16+offset];target=1 if scenario==0 else 2
            rows=[r for r in record['world']['rows'] if r['id']==target];assert len(rows)==1
            main=rows[0]['main'];keys=[k for k in ('coordinates','levels') if k in main];assert len(keys)==1
            head=main[keys[0]];assert 0<head['a']<=4294967295
            head['a']-=1
    assert expected!=baseline
    return expected

def run(overlay,baseline_root,baseline_records,output,cpu,split_schemas=False):
    """Returns the hash-bound nested receipt; never reads historical baseline outputs."""
    overlay=Path(overlay).resolve();baseline_root=Path(baseline_root).resolve();output=Path(output).absolute()
    assert not output.exists() and not any(p.is_symlink() for p in (output,*output.parents))
    os.sched_setaffinity(0,{cpu});output.mkdir()
    FA=load('suppressed_fused',HERE/'fused-adaptation.py');B=load('suppressed_build',ROOT/'experiments/t05/run.py')
    mapping=load('suppressed_slice',HERE/'materialize-controls.py')
    manifest=json.loads((overlay/'overlay.json').read_text())['sources'];assert all(sha(overlay/n)==h for n,h in manifest.items())
    original=ROOT/'experiments/s-integrate/payload.bend';core_input=overlay/'experiments/s-integrate'
    assert FA.fused_presence((core_input/'held-adapter.bend').read_text(),(core_input/'cached-payload.bend').read_text())
    assert sha(core_input/'payload.bend')==sha(original),'Protected original Raw provider changed'
    runtime_sources={}
    def visit(source):
        assert not source.is_symlink();source=source.resolve();assert source.is_relative_to(overlay)
        name=str(source.relative_to(overlay))
        if name in runtime_sources:return
        runtime_sources[name]=sha(source)
        for dependency in re.findall(r'^import\s+(\S+)',source.read_text(),re.M):
            if dependency.startswith('.'):visit(source.parent/dependency)
    visit(core_input/'measurement-bend.bend');assert runtime_sources==PC.runtime_sources(overlay),'Suppression runtime membership differs'
    runtime_digest=hashlib.sha256(json.dumps(runtime_sources,sort_keys=True,separators=(',',':')).encode()).hexdigest()
    expected=expected_noop(baseline_records);observed=[]
    source_files=[overlay/'overlay.json',core_input/'held-adapter.bend',core_input/'cached-payload.bend',core_input/'payload.bend',original,HERE/'tx-controls.bend',HERE/'original-raw-observer.bend',Path(__file__),HERE/'fused-adaptation.py']
    source_map={str(p.resolve()):sha(p) for p in source_files}
    evidence={'status':'INCOMPLETE','scope':'Finite exact unchanged affine Raw+Cache owners, true-old journal and Main marks on live fused Main path','cpu':cpu,'limits':{'checker':int(os.environ.get('BENDVY_CHECKER_SECONDS','5')),'runtime':5,'codegen':30,'clang':120},'records':144,'runtimeSources':runtime_sources,'runtimeClosureSHA256':runtime_digest,'liveMutationSites':FA.main_sites((core_input/'held-adapter.bend').read_text()),'cases':[],'sourceFiles':source_map,'rawObserverFiles':{},'rawObserverPins':{},'sourcePins':{'overlaySHA256':sha(overlay/'overlay.json'),'heldAdapterSHA256':sha(core_input/'held-adapter.bend'),'cachedPayloadSHA256':sha(core_input/'cached-payload.bend'),'fixtureSHA256':sha(HERE/'tx-controls.bend'),'protectedRawSHA256':sha(original),'adapterSHA256':sha(__file__),'fusedAdapterSHA256':sha(HERE/'fused-adaptation.py')},'baselineRecordsSHA256':hashlib.sha256(json.dumps(baseline_records,sort_keys=True,separators=(',',':')).encode()).hexdigest(),'expectedRecordsSHA256':hashlib.sha256(json.dumps(expected,sort_keys=True,separators=(',',':')).encode()).hexdigest()}
    try:
        for mode in ('cached','raw'):
            folder=output/mode;folder.mkdir();core=folder/'core'
            shutil.copytree(baseline_root/mode/'core',core)
            # The copied baseline fixture is freshly generated by the caller from this overlay.
            for name in ('held-adapter.bend','cached-payload.bend','payload.bend','uncached-payload.bend'):
                assert sha(core/name)==sha(core_input/name),'Baseline core does not match frozen overlay'
            shutil.copyfile(HERE/'original-raw-observer.bend',core/'original-raw-observer.bend')
            held=core/'held-adapter.bend';changed,sites=FA.mutation(held.read_text(),'suppressed-setter',observer='RAWNOOP')
            assert sites==evidence['liveMutationSites'] and changed.count('import Base\n')==1
            held.write_text(changed.replace('import Base\n','import Base\nimport ./original-raw-observer.bend as RAWNOOP\n',1))
            callback=core/'gate-callbacks.bend';assert callback.is_file()
            evidence['rawObserverPins'][mode]={'CP':sha(core/'cached-payload.bend'),'protectedRaw':sha(core/'payload.bend'),'HA':sha(held),'callbacks':sha(callback)}
            for p in (core/'cached-payload.bend',core/'payload.bend',core/'uncached-payload.bend',core/'original-raw-observer.bend',held,callback):evidence['rawObserverFiles'][str(p.resolve())]=sha(p)
            full=core/'cache-tx-controls.bend';text=full.read_text();lane_outputs={};programs={'Native':[],'JS':[]}
            for schema in (('motion','health') if split_schemas else ('both',)):
                entry=full;built_folder=folder
                if schema!='both':
                    built_folder=folder/schema;built_folder.mkdir();entry=core/('cache-tx-'+schema+'-controls.bend')
                    other='health' if schema=='motion' else 'motion'
                    derived=text.replace('        '+other+'_pair(scenario,False{})\n','').replace('        '+other+'_pair(scenario,True{})\n','')
                    derived,retained,removed=mapping.reachable_fixture(derived,'main');entry.write_text(derived)
                    evidence.setdefault('schemaFixtureSlices',[]).append({'getter':mode,'schema':schema,'retainedDefinitions':retained,'removedUnreachableDefinitions':removed,'records':72,'sourceSHA256':sha(entry)})
                lane_outputs[schema]={}
                for program in B.build(entry,built_folder):
                    raw=B.execute(program);lines=[json.loads(line) for line in raw.splitlines()];assert len(lines)==(144 if schema=='both' else 72)
                    backend='JS' if program.suffix=='.js' else 'Native';lane_outputs[schema][backend]=lines
                    programs[backend].append({'programPath':str(program.resolve()),'programSHA256':sha(program),'sourcePath':str(entry.resolve()),'sourceSHA256':sha(entry),'records':len(lines),'schema':schema})
            for backend in ('Native','JS'):
                if split_schemas:
                    lines=[]
                    for scenario in range(9):
                        for schema in ('motion','health'):lines.extend(lane_outputs[schema][backend][scenario*8:scenario*8+8])
                else:lines=lane_outputs['both'][backend]
                assert lines==expected,'Suppression changed fields/journal/marks, missed true-old/no-op, or live site was not reached'
                assert lines!=baseline_records;observed.append(lines)
                path=folder/(backend+'.jsonl');path.write_text(''.join(json.dumps(line,separators=(',',':'))+'\n' for line in lines))
                evidence['cases'].append({'getter':mode,'backend':backend,'compiling':True,'exactNoopFullfieldsEffects':True,'trueOldJournalPreserved':True,'journalPreserved':True,'marksPreserved':True,'records':144,'outputPath':str(path.resolve()),'outputSHA256':sha(path),'programs':programs[backend],'trueOldJournalExample':lines[2]['undo'],'marksExample':lines[2]['marks']})
        assert len(evidence['cases'])==4 and all(lines==observed[0] for lines in observed)
        assert all(sha(overlay/n)==h for n,h in manifest.items()) and all(sha(p)==h for p,h in source_map.items())
        evidence['status']=STATUS
    except Exception as error:evidence.update(status='FAIL',error=repr(error));raise
    finally:(output/'evidence.json').write_text(json.dumps(evidence,indent=2)+'\n')
    receipt=output/'evidence.json'
    return {'status':STATUS,'receipt':str(receipt.resolve()),'receiptSHA256':sha(receipt),'overlaySHA256':sha(overlay/'overlay.json')}
