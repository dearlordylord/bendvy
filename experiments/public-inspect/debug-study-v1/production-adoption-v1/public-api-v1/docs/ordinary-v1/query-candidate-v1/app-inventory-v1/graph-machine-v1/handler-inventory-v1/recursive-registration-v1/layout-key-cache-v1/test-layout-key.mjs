import assert from 'node:assert/strict';
import { layoutKey, layoutKeyStats, resetLayoutKeyCache } from './compiler/layout-key-cache.mjs';
const uncached = (a,b) => a === b || JSON.stringify(a) === JSON.stringify(b);
const cached = (a,b) => a === b || layoutKey(a) === layoutKey(b);
const box={ks:['box'],arms:null};
const word={ks:['w32'],arms:null};
const padded={ks:['box','w32','w32','w32'],arms:{Only:[box,word]}};
const nested={ks:['w32','box'],arms:{First:[word,box],Second:[box]}};
const sameNested=JSON.parse(JSON.stringify(nested));
const differentNested={ks:['w32','w32'],arms:{First:[word,word],Second:[word]}};
const reordered={ks:['w32','box'],arms:{Second:[box],First:[word,box]}};
const cases=[[box,box],[box,{ks:['box'],arms:null}],[word,box],[nested,sameNested],[nested,differentNested],[nested,reordered],[padded,JSON.parse(JSON.stringify(padded))]];
resetLayoutKeyCache();
for(let repeat=0;repeat<3;++repeat)for(const [a,b]of cases)assert.equal(cached(a,b),uncached(a,b));
const stats=layoutKeyStats();assert(stats.hits>0&&stats.misses>0);
assert.equal(cached(box,box),true);assert.deepEqual(layoutKeyStats(),stats);
resetLayoutKeyCache();assert.deepEqual(layoutKeyStats(),{hits:0,misses:0});
assert.equal(layoutKey(nested),JSON.stringify(nested));assert.deepEqual(layoutKeyStats(),{hits:0,misses:1});
console.log(JSON.stringify({stableEqualityCases:cases.length,repetitions:3,oldNewEquality:'PASS',identityShortcircuit:'PASS',reset:'PASS',observed:stats,scope:'Completed layouts only; no Bend compiler or backend invoked'}));
