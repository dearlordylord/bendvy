import {Descriptor,Fx,Schema} from '/workspace/formal-proofs/bendvy/.references/bevy-ts/packages/core/src/index.ts';
const Position=Descriptor.Component()('Position'),Ping=Descriptor.Event()('Ping');
const G=Schema.bind(Schema.fragment({components:{Position},events:{Ping}}));
const Mode=G.StateMachine('Mode',['On','Off']);
const runtime=G.Runtime.make({services:G.Runtime.services(),machines:G.Runtime.machines(G.Runtime.machine(Mode,'On'))});
const Added=G.Query({selection:{position:G.Query.read(Position)},filters:[G.Query.added(Position)]});
const Changed=G.Query({selection:{position:G.Query.read(Position)},filters:[G.Query.changed(Position)]});
const Writable=G.Query({selection:{position:G.Query.write(Position)}});
const ids=[],labels=new Map();let fastName='',slowName='',failure=false;
const list=xs=>xs.map(x=>x+',').join('');
const mapped=xs=>xs.map(id=>{if(!labels.has(id.value))throw Error('unmapped');return labels.get(id.value);});
function observer(name,slow){return G.System(name,{...(slow?{when:[G.Condition.inState(Mode,'On')]}:{}),queries:{added:Added,changed:Changed,all:G.Query({selection:{position:G.Query.read(Position)}})},removed:{position:G.System.readRemoved(Position)},despawned:{entity:G.System.readDespawned()},events:{ping:G.System.readEvent(Ping)}},({queries,removed,despawned,events})=>{
 console.log((slow?slowName:fastName)+':v='+list(queries.all.each().map(m=>m.data.position.get().x))+';a='+list(queries.added.each().map(m=>m.data.position.get().x))+';c='+list(queries.changed.each().map(m=>m.data.position.get().x))+';r='+list(mapped(removed.position.all()))+';d='+list(mapped(despawned.entity.all()))+';e='+list(events.ping.all()));
 if(slow&&failure)return Fx.fail(7);
});}
const Fast=observer('Fast',false),Slow=observer('Slow',true);
const Spawn=G.System('Spawn',{},({commands})=>{for(const x of [1,2]){const id=commands.spawn(G.Command.spawn([Position,{x}]));labels.set(id.value,ids.length);ids.push(id);}});
const write=(name,x,success=true)=>G.System(name,{queries:{positions:Writable}},({queries})=>{for(const m of queries.positions.each())m.data.position.set({x});if(!success)return Fx.fail(9);});
const Insert=G.System('Insert',{},({commands})=>{commands.insert(ids[0],[Position,{x:9}]);});
const Cleanup=G.System('Cleanup',{},({commands})=>{commands.remove(ids[0],Position);commands.despawn(ids[1]);});
const Reinsert=G.System('Reinsert',{},({commands})=>{commands.insert(ids[0],[Position,{x:5}]);});
const Emit=G.System('Emit',{events:{ping:G.System.writeEvent(Ping)}},({events})=>{events.ping.emit(7);});
const Off=G.System('Off',{nextMachines:{mode:G.System.nextState(Mode)}},({nextMachines})=>{nextMachines.mode.set('Off');});
const On=G.System('On',{nextMachines:{mode:G.System.nextState(Mode)}},({nextMachines})=>{nextMachines.mode.set('On');});
const tick=(...steps)=>runtime.tick(G.Schedule(...steps));
fastName='fast:pending';tick(Spawn,Fast);
fastName='fast:spawn';tick(G.Schedule.applyDeferred(),Fast);
fastName='fast:write';tick(write('Write',11),Fast);
slowName='slow:late';tick(Slow);
fastName='fast:insert-pending';tick(Insert,Fast);
fastName='fast:overwrite';tick(G.Schedule.applyDeferred(),Fast);
tick(Off,G.Schedule.applyStateTransitions());tick(write('SkippedChange',21),G.System('Emit6',{events:{ping:G.System.writeEvent(Ping)}},({events})=>{events.ping.emit(6);}),Slow);
slowName='slow:changed-after-skip';fastName='fast:write-held';tick(On,G.Schedule.applyStateTransitions(),Slow,Fast);
tick(write('FailedWrite',100,false));fastName='fast:failed-write';tick(Fast);
fastName='fast:before-failed-reader';tick(write('Write31',31),Fast);
slowName='slow:failed';failure=true;tick(Slow);
slowName='slow:retry';failure=false;tick(Slow);
fastName='fast:cleanup-pending';tick(Cleanup,Fast);
fastName='fast:cleanup';tick(G.Schedule.applyDeferred(),Fast);
tick();tick();tick();tick(Off,G.Schedule.applyStateTransitions());tick(Emit,Slow);
slowName='slow:after-skip-failed';failure=true;tick(On,G.Schedule.applyStateTransitions(),Slow);
slowName='slow:removal-retry';failure=false;fastName='fast:event-held';tick(Slow,Fast);
fastName='fast:reinsert';tick(Reinsert,G.Schedule.applyDeferred(),Fast);
slowName='slow:reinsert';tick(Slow);
fastName='fast:empty';slowName='slow:empty';tick(Fast,Slow);
